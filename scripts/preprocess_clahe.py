#!/usr/bin/env python3
"""
scripts/preprocess_clahe.py
針對 data/dataset/ (train / val / test) 的影像於 LAB 色彩空間 L 通道執行
CLAHE (Contrast Limited Adaptive Histogram Equalization, clipLimit=2.0, tileGridSize=(8,8))，
輸出至獨立目錄 data/dataset_clahe/ 並產生 configs/traffic_facility_clahe.yaml，
供 Exp 10 使用，完全不覆蓋或影響 Exp 1~9 的原始影像。
"""

import os
import shutil
import argparse
import cv2

DEFAULT_NAMES = [
    "traffic_light",
    "crosswalk",
    "two_stage_left_turn_box",
    "Sign_follow",
    "Sign_prohibit",
    "Sign_limit",
]


def apply_clahe_lab(img_bgr, clahe):
    """在 LAB 色彩空間對 L (亮度) 通道套用 CLAHE，保留原始色度資訊。"""
    lab = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2LAB)
    l_ch, a_ch, b_ch = cv2.split(lab)
    l_eq = clahe.apply(l_ch)
    merged = cv2.merge((l_eq, a_ch, b_ch))
    return cv2.cvtColor(merged, cv2.COLOR_LAB2BGR)


def write_clahe_yaml(yaml_path: str, dst_rel_root: str = "../nchu-research-method-traffic-violation-dataset/data/dataset_clahe"):
    os.makedirs(os.path.dirname(yaml_path), exist_ok=True)
    content = (
        "# NCHU Research Method - Taiwan Traffic Violation & Facility Dataset Config (CLAHE Preprocessed)\n"
        "# Generated by scripts/preprocess_clahe.py for Exp 10\n\n"
        f"train: {dst_rel_root}/train/images\n"
        f"val: {dst_rel_root}/val/images\n"
        f"test: {dst_rel_root}/test/images\n\n"
        f"nc: {len(DEFAULT_NAMES)}\n\n"
        f"names: {DEFAULT_NAMES}\n"
    )
    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(content)


def preprocess_dataset(
    src_dir: str = "data/dataset",
    dst_dir: str = "data/dataset_clahe",
    yaml_out: str = "configs/traffic_facility_clahe.yaml",
    clip_limit: float = 2.0,
    tile_size: int = 8,
):
    if not os.path.exists(src_dir):
        raise FileNotFoundError(f"找不到來源資料集目錄: {src_dir}")

    clahe = cv2.createCLAHE(clipLimit=clip_limit, tileGridSize=(tile_size, tile_size))
    image_exts = (".jpg", ".jpeg", ".png", ".bmp")
    total_processed = 0

    for split in ["train", "val", "test"]:
        src_img_dir = os.path.join(src_dir, split, "images")
        src_lbl_dir = os.path.join(src_dir, split, "labels")
        dst_img_dir = os.path.join(dst_dir, split, "images")
        dst_lbl_dir = os.path.join(dst_dir, split, "labels")

        if not os.path.exists(src_img_dir):
            print(f"⚠️ 略過不存在的目錄: {src_img_dir}")
            continue

        os.makedirs(dst_img_dir, exist_ok=True)
        os.makedirs(dst_lbl_dir, exist_ok=True)

        img_files = sorted(f for f in os.listdir(src_img_dir) if f.lower().endswith(image_exts))
        for fname in img_files:
            src_path = os.path.join(src_img_dir, fname)
            dst_path = os.path.join(dst_img_dir, fname)
            img = cv2.imread(src_path)
            if img is None:
                raise RuntimeError(f"無法讀取影像: {src_path}")
            enhanced = apply_clahe_lab(img, clahe)
            cv2.imwrite(dst_path, enhanced)
            total_processed += 1

        if os.path.exists(src_lbl_dir):
            for fname in os.listdir(src_lbl_dir):
                if fname.lower().endswith(".txt"):
                    shutil.copy2(os.path.join(src_lbl_dir, fname), os.path.join(dst_lbl_dir, fname))

        print(f"  ✅ [{split}] 已完成 {len(img_files)} 張影像之 LAB-CLAHE 增強與標註同步")

    classes_src = os.path.join(src_dir, "classes.txt")
    if os.path.exists(classes_src):
        shutil.copy2(classes_src, os.path.join(dst_dir, "classes.txt"))

    if yaml_out:
        write_clahe_yaml(yaml_out)
        print(f"📄 已產生設定檔: {yaml_out}")

    print(
        f"\n🎉 CLAHE 前處理完成！共處理 {total_processed} 張影像 "
        f"(clipLimit={clip_limit}, tileGridSize=({tile_size},{tile_size})) -> {dst_dir}"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="LAB 空間 L 通道 CLAHE 影像前處理工具")
    parser.add_argument("--src", type=str, default="data/dataset", help="來源切分資料集目錄")
    parser.add_argument("--dst", type=str, default="data/dataset_clahe", help="輸出 CLAHE 資料集目錄")
    parser.add_argument("--yaml-out", type=str, default="configs/traffic_facility_clahe.yaml", help="輸出 YAML 路徑")
    parser.add_argument("--clip-limit", type=float, default=2.0, help="CLAHE clipLimit (預設 2.0)")
    parser.add_argument("--tile-size", type=int, default=8, help="CLAHE tileGridSize (預設 8)")
    args = parser.parse_args()

    preprocess_dataset(
        src_dir=args.src,
        dst_dir=args.dst,
        yaml_out=args.yaml_out,
        clip_limit=args.clip_limit,
        tile_size=args.tile_size,
    )
